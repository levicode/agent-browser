//! Custody tests use the real broker + constructor and a scripted CDP socket.
//! They prove neither Chrome behavior nor completed public surface wiring.
use super::super::super::super::client_protocol::Effects;
use super::super::super::super::client_session::ClientSession;
use super::super::super::interop_preparation::InteropPreparation;
use super::*;

fn ticket() -> String {
    uuid::Uuid::new_v4().to_string()
}
fn args(id: &str) -> serde_json::Map<String, Value> {
    json!({"preparationId":id}).as_object().unwrap().clone()
}
async fn prepare(
    mode: Mode,
    timeout_ms: u64,
) -> (
    Arc<InteropPreparation>,
    Arc<ClientSession>,
    Arc<tokio::sync::Mutex<Option<OwnedBrowser>>>,
    String,
    Peer,
) {
    let (manager, peer) = peer(mode).await;
    let broker = Arc::new(ClientSession::new());
    let owner = Arc::new(tokio::sync::Mutex::new(None));
    let custody = InteropPreparation::new(owner.clone(), broker.clone());
    let op = broker.admit(1, 1, timeout_ms).unwrap();
    assert!(broker.start(1, 1).unwrap());
    let id = ticket();
    let mut manager = Some(manager);
    custody
        .prepare(
            id.clone(),
            &mut manager,
            op,
            Arc::new(tokio::sync::Mutex::new(())).lock_owned().await,
        )
        .await
        .unwrap();
    assert!(manager.is_none());
    broker.settle(1, 1, Effects::Completed).unwrap();
    (custody, broker, owner, id, peer)
}
fn admit(
    custody: &InteropPreparation,
    broker: &ClientSession,
    id: &str,
    sequence: u64,
) -> OperationLease {
    let cap = custody.admission_deadline_cap(1, "scope.interop.adopt", &args(id));
    let op = broker
        .admit_callback_capped(1, sequence, 60000, None, cap)
        .unwrap();
    assert!(broker.start(1, sequence).unwrap());
    op
}

#[tokio::test]
async fn settled_prepare_later_real_adoption_and_joined_exact_cleanup() {
    let (custody, broker, owner, id, peer) = prepare(Mode::Valid, 5000).await;
    assert_eq!(broker.cancel(1, 1), Err(ProtocolError::OperationMissing));
    assert_eq!(
        custody.admission_deadline_cap(1, "ordinary", &args("wrong")),
        Ok(None)
    );
    assert_eq!(
        custody.admission_deadline_cap(1, "scope.interop.adopt", &args("wrong")),
        Err(ProtocolError::StaleScope)
    );
    let op = admit(&custody, &broker, &id, 2);
    custody
        .adopt(1, &id, "pw-context".into(), "pw-page".into(), op)
        .await
        .unwrap();
    broker.settle(1, 2, Effects::Completed).unwrap();
    {
        let owner = owner.lock().await;
        let resource = owner.as_ref().unwrap();
        assert!(resource.runtime.is_none(), "this is not scope publication");
        assert_eq!(resource.context_id, "pw-context");
        assert_eq!(resource.manager.active_target_id().unwrap(), "pw-page");
    }
    custody.abort(1, &id).await.unwrap();
    assert!(owner.lock().await.is_none());
    assert_no_host_destruction(&peer);
    assert_eq!(
        methods(&peer)
            .iter()
            .filter(|m| *m == "Target.disposeBrowserContext")
            .count(),
        1
    );
    joined(peer).await;
}

#[tokio::test]
async fn idle_expiry_uses_independent_lifetime_after_prepare_settlement() {
    let (custody, _broker, owner, id, peer) = prepare(Mode::Valid, 200).await;
    // EOF is generated by actual cleanup, not by the expired RPC's dropped watch.
    joined(peer).await;
    assert_eq!(
        custody.admission_deadline_cap(1, "scope.interop.adopt", &args(&id)),
        Err(ProtocolError::StaleScope)
    );
    custody.shutdown().await.unwrap();
    assert!(owner.lock().await.is_none());
}

#[tokio::test]
async fn mismatch_does_not_cancel_owner_and_dispatch_rechecks_after_abort() {
    let (custody, broker, owner, id, peer) = prepare(Mode::Valid, 5000).await;
    let op = admit(&custody, &broker, &id, 2);
    assert_eq!(
        custody.abort(1, "wrong").await,
        Err(ProtocolError::StaleScope)
    );
    assert!(custody
        .admission_deadline_cap(1, "scope.interop.adopt", &args(&id))
        .is_ok());
    custody.abort(1, &id).await.unwrap();
    assert_eq!(
        custody
            .adopt(1, &id, "pw-context".into(), "pw-page".into(), op)
            .await,
        Err(ProtocolError::StaleScope)
    );
    assert!(owner.lock().await.is_none());
    assert_no_host_destruction(&peer);
    assert!(!methods(&peer).contains(&"Target.disposeBrowserContext".to_owned()));
    joined(peer).await;
}

#[tokio::test]
async fn dropped_adopt_and_abort_waiters_do_not_lose_cleanup_join() {
    let (custody, broker, owner, id, mut peer) = prepare(Mode::HoldAfterAttach, 5000).await;
    let op = admit(&custody, &broker, &id, 2);
    let adopting = {
        let custody = custody.clone();
        let id = id.clone();
        tokio::spawn(async move {
            custody
                .adopt(1, &id, "pw-context".into(), "pw-page".into(), op)
                .await
        })
    };
    tokio::time::timeout(Duration::from_secs(2), peer.held.recv())
        .await
        .unwrap()
        .unwrap();
    adopting.abort();
    let _ = adopting.await;
    let aborting = {
        let custody = custody.clone();
        let id = id.clone();
        tokio::spawn(async move { custody.abort(1, &id).await })
    };
    // A later shutdown joins the same supervisor even if this abort RPC is gone.
    tokio::task::yield_now().await;
    aborting.abort();
    let _ = aborting.await;
    let _ = peer.release.send(());
    custody.shutdown().await.unwrap();
    assert!(owner.lock().await.is_none());
    assert_no_host_destruction(&peer);
    assert!(methods(&peer).contains(&"Target.disposeBrowserContext".to_owned()));
    joined(peer).await;
}

#[tokio::test]
async fn failed_cleanup_keeps_original_owner_and_rejects_replacement() {
    let (custody, broker, owner, id, peer) = prepare(Mode::DisposeFailure, 5000).await;
    let op = admit(&custody, &broker, &id, 2);
    custody
        .adopt(1, &id, "pw-context".into(), "pw-page".into(), op)
        .await
        .unwrap();
    broker.settle(1, 2, Effects::Completed).unwrap();
    assert_eq!(
        custody.abort(1, &id).await,
        Err(ProtocolError::CleanupFailed)
    );
    assert_eq!(
        owner.lock().await.as_ref().unwrap().context_id,
        "pw-context"
    );
    let (next, next_peer) = super::peer(Mode::Valid).await;
    let mut next = Some(next);
    let op = broker.admit(1, 3, 5000).unwrap();
    assert!(matches!(
        custody
            .prepare(
                ticket(),
                &mut next,
                op,
                Arc::new(tokio::sync::Mutex::new(())).lock_owned().await
            )
            .await,
        Err(ProtocolError::ScopeUnavailable)
    ));
    assert!(next.is_some(), "rejected candidate stays with its caller");
    next.as_mut().unwrap().close().await.unwrap();
    assert_no_host_destruction(&peer);
    joined(peer).await;
    joined(next_peer).await;
}

#[tokio::test]
async fn owned_manager_cleanup_preserves_real_process_close_and_wait_path() {
    let (mut manager, peer) = peer(Mode::Valid).await;
    let waited = manager.install_cleanup_process_witness();
    let broker = Arc::new(ClientSession::new());
    let owner = Arc::new(tokio::sync::Mutex::new(None));
    let custody = InteropPreparation::new(owner.clone(), broker.clone());
    let op = broker.admit(1, 1, 5000).unwrap();
    let id = ticket();
    custody
        .prepare(
            id.clone(),
            &mut Some(manager),
            op,
            Arc::new(tokio::sync::Mutex::new(())).lock_owned().await,
        )
        .await
        .unwrap();
    broker.settle(1, 1, Effects::Completed).unwrap();
    custody.shutdown().await.unwrap();
    assert!(waited.load(std::sync::atomic::Ordering::SeqCst));
    assert_eq!(
        methods(&peer)
            .iter()
            .filter(|m| *m == "Browser.close")
            .count(),
        1
    );
    assert!(!methods(&peer).contains(&"Target.disposeBrowserContext".to_owned()));
    assert!(owner.lock().await.is_none());
    joined(peer).await;
}

#[tokio::test]
async fn actual_browser_shutdown_signals_preparation_before_lifecycle_join() {
    use super::super::super::super::client_transport::ClientExecutor;
    let (manager, peer) = peer(Mode::Valid).await;
    let broker = Arc::new(ClientSession::new());
    let browser = super::super::super::ClientBrowser::new(broker.clone());
    let id = ticket();
    let op = broker.admit(1, 1, 5000).unwrap();
    let mut manager = Some(manager);
    browser
        .interop_preparation
        .prepare(
            id.clone(),
            &mut manager,
            op,
            browser.lifecycle.clone().lock_owned().await,
        )
        .await
        .unwrap();
    broker.settle(1, 1, Effects::Completed).unwrap();
    assert!(browser
        .admission_deadline_cap(1, "scope.interop.adopt", &args(&id))
        .unwrap()
        .is_some());
    assert_eq!(
        browser.admission_deadline_cap(1, "scope.interop.adopt", &args("wrong")),
        Err(ProtocolError::StaleScope)
    );
    tokio::time::timeout(Duration::from_secs(2), browser.shutdown())
        .await
        .unwrap()
        .unwrap();
    assert!(browser.owner.lock().await.is_none());
    assert_no_host_destruction(&peer);
    joined(peer).await;
}

#[tokio::test]
async fn dropped_prepare_waiter_keeps_resource_until_ready_failure_cleanup() {
    let (manager, mut peer) = peer(Mode::HoldPreparation).await;
    let broker = Arc::new(ClientSession::new());
    let owner = Arc::new(tokio::sync::Mutex::new(None));
    let custody = InteropPreparation::new(owner.clone(), broker.clone());
    let op = broker.admit(1, 1, 5000).unwrap();
    let id = ticket();
    let preparing = {
        let custody = custody.clone();
        let id = id.clone();
        tokio::spawn(async move {
            custody
                .prepare(
                    id,
                    &mut Some(manager),
                    op,
                    Arc::new(tokio::sync::Mutex::new(())).lock_owned().await,
                )
                .await
        })
    };
    tokio::time::timeout(Duration::from_secs(2), peer.held.recv())
        .await
        .unwrap()
        .unwrap();
    preparing.abort();
    let _ = preparing.await;
    let _ = peer.release.send(());
    // Cleanup runs even though no caller is left to receive prepare's ACK.
    tokio::time::timeout(Duration::from_secs(2), &mut peer.task)
        .await
        .unwrap()
        .unwrap();
    custody.abort(1, &id).await.unwrap();
    assert!(owner.lock().await.is_none());
    assert_no_host_destruction(&peer);
}

#[tokio::test]
async fn reused_manager_adoption_uses_new_rpc_lease_after_prepare_has_settled() {
    let (manager, old, peer) = retained_manager(true).await;
    let broker = Arc::new(ClientSession::new());
    let owner = Arc::new(tokio::sync::Mutex::new(None));
    let custody = InteropPreparation::new(owner.clone(), broker.clone());
    let prepare = broker.admit(1, 1, 5000).unwrap();
    assert!(broker.start(1, 1).unwrap());
    let deadline = prepare.deadline;
    let id = ticket();
    let mut manager = Some(manager);
    custody
        .prepare(
            id.clone(),
            &mut manager,
            prepare,
            Arc::new(tokio::sync::Mutex::new(())).lock_owned().await,
        )
        .await
        .unwrap();
    broker.settle(1, 1, Effects::Completed).unwrap();
    assert_eq!(broker.cancel(1, 1), Err(ProtocolError::OperationMissing));
    assert!(old.replacement_ready());
    let operation = admit(&custody, &broker, &id, 2);
    assert_eq!(operation.deadline, deadline);
    custody
        .adopt(1, &id, "pw-context".into(), "pw-page".into(), operation)
        .await
        .unwrap();
    {
        let owner = owner.lock().await;
        let resource = owner.as_ref().unwrap();
        let new_owner = resource.manager.client.debt_ledger().unwrap();
        assert!(!Arc::ptr_eq(&old, &new_owner));
        assert_eq!(
            new_owner.initialization_deadline("Target.getBrowserContexts"),
            Some(deadline)
        );
        // Cancellation of the genuine later RPC, not the settled prepare, must
        // immediately revoke unpublished application/metadata submissions.
        broker.cancel(1, 2).unwrap();
        assert!(resource
            .manager
            .client
            .send_command("Target.getBrowserContexts", Some(json!({})), None)
            .await
            .is_err());
    }
    broker.settle(1, 2, Effects::Completed).unwrap();
    custody.abort(1, &id).await.unwrap();
    assert!(owner.lock().await.is_none());
    joined(peer).await;
}
